const POPTART = [["#d787af", "#d70087"], ["#875f5f", "#ffd7af"], ["#87af5f", "#ffffff"], ["#ffff87", "#ff8700"], ["#87ffd7", "#ff5f87"], ["#ffffff", "#00afff"]]; // strawberry, chocolate, matcha, lemon, mint, vanilla
